const sum = (values) => values.reduce((a, b) => a + b, 0);
const near = (a, b, tolerance, message) => assert.ok(Math.abs(a - b) <= tolerance, `${message ?? ""} ${a} vs ${b}`);

const day = dayModel(ONE_DAY);
const flare = flareModel(FLARE);
const states = DAY_STEPS.map((_, i) => dayState(day, i));

describe("the committed samples", () => {
  it("are small plain-data modules", () => {
    const bytes = ["one-day.js", "flare.js"].map((name) => statSync(new URL(`../public/js/method/samples/${name}`, import.meta.url)).size);
    assert.ok(sum(bytes) < 40 * 1024, `${sum(bytes)} bytes`);
    assert.match(moduleText("X", { a: 1, rows: [[1], [2]] }), /^\/\/ Generated by .*\nexport const X = \{\n {2}"a": 1,\n {2}"rows": \[\n {4}\[1\],\n {4}\[2\]\n {2}\],\n\};\n$/);
  });

  it("hold one autumn day in the Nile Delta with both cameras, gas flares and every pipeline decision", () => {
    assert.equal(ONE_DAY.region.id, "nile_delta");
    assert.match(ONE_DAY.date, /^201[2-9]-(09|10|11)-\d\d$/);
    assert.ok(ONE_DAY.rows.length >= 30 && ONE_DAY.rows.length <= 80, String(ONE_DAY.rows.length));
    const sats = new Set(ONE_DAY.rows.map((row) => row.sat));
    assert.ok(sats.has("Aqua") && sats.has("S-NPP"));
    const [west, south, east, north] = ONE_DAY.region.bbox;
    for (const row of ONE_DAY.rows) {
      assert.ok(row.lon >= west && row.lon <= east && row.lat >= south && row.lat <= north, "in the box");
      assert.match(row.time, /^\d\d:\d\d$/);
      assert.equal(row.role === "non_vegetation", row.type !== 0, "the role follows the FIRMS type");
      if (row.role === "snpp") assert.ok(row.weight > 0 && row.weight < 1 && row.label !== null, "in-series VIIRS rows carry a weight and a label");
      else assert.equal(row.weight, null);
    }
    assert.ok(ONE_DAY.rows.some((row) => row.type === 2), "at least one hot spot is not a vegetation fire");
    assert.ok(day.rows.some((row) => row.modis && row.scan > 0 && row.track > 0));
    assert.equal(ONE_DAY.duplicates.day, 0);
    assert.equal(ONE_DAY.month.days.length, 30);
    near(sum(ONE_DAY.month.days), ONE_DAY.month.total, 0.002, "the days add up to the month");
  });

  it("works the 5 km cell out with the shared 0.05° grid", () => {
    for (const row of day.rows) assert.equal(row.cell, cellOf(row.lat, row.lon));
  });

  it("hold 90 days around a known flare with the pipeline's rule", () => {
    assert.equal(FLARE.days, 90);
    assert.deepEqual({ ...FLARE.rule, radiusKm: undefined }, { spotDeg: 0.004, minDays: 20, windowDays: 90, radiusKm: undefined });
    assert.equal(FLARE.source.type, 2);
    assert.equal(flare.detections.length, FLARE.rows.length, "every row falls inside the box");
    for (let i = 1; i < FLARE.rows.length; i += 1) assert.ok(FLARE.rows[i][0] >= FLARE.rows[i - 1][0], "rows in time order");
  });

  it("clips the land to the box", () => {
    const corners = (ring) => ring.map((p) => p.join(",")).sort();
    assert.deepEqual(corners(clipRing([[0, 0], [4, 0], [4, 4], [0, 4]], [1, 1, 2, 3])), ["1,1", "1,3", "2,1", "2,3"]);
    assert.deepEqual(corners(clipRing([[0, 0], [3, 0], [0, 3]], [1, 0, 4, 4])), ["1,0", "1,2", "3,0"]);
    for (const ring of ONE_DAY.land) {
      for (const [lon, lat] of ring) assert.ok(lon >= 29.5 && lon <= 32.5 && lat >= 29.8 && lat <= 31.8);
    }
  });
});

describe("one day, step by step", () => {
  it("keeps the counts adding up after each step", () => {
    const aside = day.rows.filter((row) => row.aside).length;
    for (const state of states) {
      const c = state.counters;
      assert.equal(c.detections + c.setAside + c.duplicates, c.arrived, state.title);
      assert.equal(c.modis + c.viirs + aside, c.arrived, state.title);
      assert.equal(c.setAside, state.step >= STEP.clean ? aside : 0, state.title);
    }
    assert.equal(states[0].counters.arrived, ONE_DAY.rows.length);
    for (const state of states.slice(STEP.match)) {
      const { saw, missed, unseen } = state.match;
      assert.equal(saw + missed + unseen, state.counters.viirs);
    }
    assert.deepEqual(states[STEP.match].match, { saw: 3, missed: 43, unseen: 0 });
    assert.equal(states[STEP.clean].match, null);
  });

  it("weighs the day to the sum of its weights, which is the day's bar of the month", () => {
    const weights = sum(day.rows.filter((row) => row.inSeries).map((row) => row.weight));
    assert.equal(states[STEP.match].counters.weighed, null);
    near(states[STEP.weigh].counters.weighed, weights, 1e-9);
    near(states[STEP.weigh].counters.weighed, ONE_DAY.month.days[day.dayIndex], 0.003, "the database's total for the day");
    const add = states[STEP.add];
    near(sum(add.cells.map((cell) => cell.sum)), weights, 1e-9, "the 5 km squares");
    assert.equal(sum(add.cells.map((cell) => cell.n)), add.counters.viirs);
    near(add.day.share, weights / ONE_DAY.month.total, 1e-12);
    assert.match(add.text, /3\.65 for the day\. September 2017 comes to 124\.5 on the calendar, and this day is 2\.9% of it\./);
  });

  it("logs what each step did, one step's lines at a time", () => {
    for (let i = 1; i < states.length; i += 1) {
      const before = states[i - 1].log.map((line) => line.text);
      assert.deepEqual(states[i].log.slice(0, before.length).map((line) => line.text), before);
      assert.ok(states[i].log.length > before.length);
      assert.ok(states[i].log.every((line, k) => line.latest === k >= before.length));
    }
    const lines = states[STEP.add].log.map((line) => line.text);
    assert.ok(lines.includes("Removed 0 duplicates: this day had none."));
    assert.ok(lines.includes("Set aside 14 steady heat sources (gas flares and the like)."));
    assert.match(states[STEP.clean].text, /no duplicates to remove/);
  });

  it("clamps the step and describes it for screen readers", () => {
    assert.equal(dayState(day, -3).step, 0);
    assert.equal(dayState(day, 99).step, DAY_STEPS.length - 1);
    assert.match(describeDay(day, states[STEP.weigh]), /^Step 4 of 5: Weigh\. .* 53 detections on the map, 14 set aside\. Weighed total 3\.65\.$/);
  });

  it("tells the picked detection's story at each step", () => {
    const pick = defaultPick(day);
    const row = day.rows[pick];
    assert.equal(row.match, "saw");
    assert.equal(pickText(day, states[STEP.arrive], pick), "S-NPP (VIIRS), day pass at 11:13 UTC, fire strength 14 MW.");
    assert.match(pickText(day, states[STEP.match], pick), /saw it, in a square it shares with another VIIRS fire\.$/);
    assert.match(pickText(day, states[STEP.weigh], pick), /Counts as 0\.27 of a MODIS detection\.$/);
    assert.match(pickText(day, states[STEP.add], pick), /Its 5 km square adds up to [\d.]+ from \d+ fires?\.$/);
    const aside = day.rows.find((r) => r.aside).index;
    assert.match(pickText(day, states[STEP.clean], aside), /gas flare: set aside\.$/);
    const modis = day.rows.find((r) => r.modis).index;
    assert.match(pickText(day, states[STEP.match], modis), /Its square is about [\d.]+ by [\d.]+ km\.$/);
    assert.match(pickText(day, states[STEP.add], modis), /only the yardstick\.$/);
    assert.equal(pickText(day, states[0], 999), "");
  });

  it("fills the scientists' fold from the sample", () => {
    const html = dayScienceHtml(ONE_DAY);
    assert.match(html, /7 MODIS and 60 VIIRS/);
    assert.match(html, /0 duplicates on this day and 0 on the days either side/);
    assert.match(html, /calendar value, 124\.50/);
  });
});

describe("one day, drawn", () => {
  const dots = (svg) => count(svg, /data-i="/g);

  it("draws both views at every step, named and without gaps", () => {
    for (const state of states) {
      for (const [view, width] of [["map", 320], ["map", 640], ["closeUp", 280]]) {
        const svg = dayMapSvg(day, state, { width, view, pick: defaultPick(day) });
        assert.ok(!svg.includes("NaN") && !svg.includes("undefined"), `${state.id} ${view}`);
        assert.deepEqual(findings(svg), [], `${state.id} ${view}`);
        assert.match(svg, new RegExp(`viewBox="0 0 ${width} `));
        assert.equal(count(svg, /class="ex-pick"/g), 1, `${state.id} ${view}: the picked detection is ringed`);
      }
    }
  });

  it("moves the gas flares aside, then folds the VIIRS fires into 5 km squares", () => {
    const at = (step) => dayMapSvg(day, states[step], { width: 640 });
    assert.equal(dots(at(STEP.arrive)), 67);
    assert.equal(count(at(STEP.arrive), /ex-aside/g), 0);
    assert.equal(count(at(STEP.clean), /ex-dot ex-aside/g), 14);
    assert.equal(count(at(STEP.match), /class="ex-foot"/g), 7);
    assert.equal(count(at(STEP.match), /ex-saw/g), 3);
    assert.equal(count(at(STEP.weigh), /ex-reference/g), 7);
    assert.equal(dots(at(STEP.add)), 7 + 14, "VIIRS dots leave the main map for their squares");
    assert.equal(count(at(STEP.add), /class="ex-cell/g), day.cells.length);
  });

  it("animates only the change the step makes, when asked", () => {
    const svg = (step, animate) => dayMapSvg(day, states[step], { width: 640, animate });
    assert.equal(count(svg(STEP.clean, true), /ex-anim-aside/g), 14);
    assert.equal(count(svg(STEP.clean, false), /ex-anim/g), 0);
    assert.equal(count(svg(STEP.match, true), /ex-anim/g), 0);
    assert.equal(count(svg(STEP.weigh, true), /ex-anim-shrink/g), 46);
    assert.ok(count(svg(STEP.add, true), /ex-anim-in/g) > 0);
  });

  it("writes the 5 km sums in the close-up and shows MODIS's real square there", () => {
    const match = dayMapSvg(day, states[STEP.match], { width: 300, view: "closeUp" });
    const foot = /class="ex-foot" x="[\d.-]+" y="[\d.-]+" width="([\d.]+)" height="([\d.]+)"/.exec(match);
    assert.ok(foot && Number(foot[1]) > 30, "about 1 km in an 8 km close-up 300 px wide");
    assert.match(dayMapSvg(day, states[STEP.add], { width: 300, view: "closeUp" }), /class="ex-cell-sum"[^>]*>\d\.\d\d</);
  });

  it("keeps the set-aside strip inside the map", () => {
    for (const width of [320, 640]) {
      const places = trayPlaces(14, width, 100);
      assert.ok(places.every((p) => p.x > 60 && p.x <= width - 10 && p.y === 115));
    }
    near(mapHeight([29.5, 29.8, 32.5, 31.8], 600), 465.8, 0.5);
  });

  it("marks the day on the month's bars once it is added", () => {
    const before = monthSvg(day, states[STEP.weigh], { width: 400 });
    const after = monthSvg(day, states[STEP.add], { width: 400 });
    assert.equal(count(before, /ex-bar-wait/g), 1);
    assert.equal(count(after, /ex-bar-day/g), 1);
    assert.equal(count(after, /<rect/g), 30);
    assert.deepEqual(findings(after), []);
    assert.match(monthText(day, states[STEP.arrive]), /Step 5 adds 13 September to it\.$/);
    assert.match(monthText(day, states[STEP.add]), /^13 September adds 3\.65 to September 2017, which comes to 124\.5 on the calendar: 2\.9% of it\.$/);
  });
});

describe("spotting the gas flare, day by day", () => {
  const unit = Math.round(FLARE.rule.spotDeg * 1e5);
  /** Distinct days a spot showed heat up to `d`, straight from the rows. */
  const daysSeen = (row, col, d) =>
    new Set(FLARE.rows.filter(([x, dLat, dLon]) => x <= d && Math.floor(dLat / unit) === row && Math.floor(dLon / unit) === col).map(([x]) => x)).size;

  it("counts each spot's distinct days, never going down", () => {
    let previous = new Map();
    for (let d = 1; d <= FLARE.days; d += 1) {
      const state = flareState(flare, d);
      for (const spot of state.spots) {
        assert.equal(spot.seen, daysSeen(spot.row, spot.col, d), `day ${d} spot ${spot.row},${spot.col}`);
        assert.ok(spot.seen >= (previous.get(`${spot.row},${spot.col}`) ?? 0));
      }
      previous = new Map(state.spots.map((spot) => [`${spot.row},${spot.col}`, spot.seen]));
    }
    assert.equal(sum(Array.from({ length: FLARE.days }, (_, i) => flareState(flare, i + 1).today.length)), FLARE.rows.length);
  });

  it("flags the flare's spot on the day it reaches 20, and not a day before", () => {
    const unitRow = Math.floor(Math.round(FLARE.source.lat * 1e5) / unit) - FLARE.box.row0;
    const unitCol = Math.floor(Math.round(FLARE.source.lon * 1e5) / unit) - FLARE.box.col0;
    const source = flare.spots.find((spot) => spot.row === unitRow && spot.col === unitCol);
    assert.ok(source && source.days.length >= 20, "the known flare's own spot shows heat on 20 days or more");
    const flaggedOn = source.days[19];
    const on = (d) => flareState(flare, d).spots.find((spot) => spot.row === unitRow && spot.col === unitCol);
    assert.deepEqual([on(flaggedOn - 1).seen, on(flaggedOn - 1).flagged], [19, false]);
    assert.deepEqual([on(flaggedOn).seen, on(flaggedOn).flagged], [20, true]);
    assert.ok(flareState(flare, flaggedOn).newlyFlagged.some((spot) => spot.row === unitRow && spot.col === unitCol));
    assert.match(flareNews(flare, flareState(flare, flaggedOn)), /shown heat on 20 days/);
  });

  it("flags every spot with 20 days or more by the last day, and only those", () => {
    const last = flareState(flare, FLARE.days);
    assert.equal(last.flagged, flare.spots.filter((spot) => spot.days.length >= 20).length);
    assert.equal(last.flagged, 4);
    assert.deepEqual(
      flare.spots.filter((spot) => spot.days.length >= 20).map((spot) => spot.days[19]).sort((a, b) => a - b),
      [39, 41, 59, 62],
    );
    assert.equal(flareState(flare, 38).flagged, 0);
    assert.equal(flareState(flare, 0).day, 1);
    assert.equal(flareState(flare, 500).day, FLARE.days);
    assert.equal(flareState(flare, 39).date, "2026-09-23");
  });

  it("draws the box with flagged spots, today's hot spots and a name", () => {
    for (const d of [1, 39, 62, 90]) {
      const state = flareState(flare, d);
      const svg = flareSvg(flare, state, { width: 360, animate: true });
      assert.ok(!svg.includes("NaN"));
      assert.deepEqual(findings(svg), [], `day ${d}`);
      assert.equal(count(svg, /class="ex-spot-flag"/g), state.flagged);
      assert.equal(count(svg, /Steady heat source/g), state.flagged > 0 ? 1 : 0);
      assert.equal(count(svg, /class="ex-today/g), state.today.length);
      assert.equal(count(svg, /ex-flash/g), state.today.length);
    }
    assert.match(describeFlare(flare, flareState(flare, 62)), /4 spots flagged as steady heat sources\.$/);
    assert.match(flareScienceHtml(FLARE), /at least 20 distinct days in the 90 days/);
    assert.match(flareScienceHtml(FLARE), /set aside 118 of these 140 detections/);
  });
});

describe("the widgets on the page", () => {
  const ids = (doc, id) => doc.getElementById(id);
  const mount = (options) => {
    const doc = parseHtml(HTML);
    return { doc, widgets: mountExplorables(/** @type {any} */ (doc), options) };
  };

  it("lists every widget module and both samples for preloading", () => {
    for (const href of ["/js/method/explorables.js", "/js/method/samples/one-day.js", "/js/method/samples/flare.js"]) {
      assert.ok(HTML.includes(`<link rel="modulepreload" href="${href}">`), href);
    }
  });

  it("steps with Back, Next and Reset, and passes the checker at every step", () => {
    const { doc, widgets } = mount({ reducedMotion: false });
    assert.equal(ids(doc, "day-title").textContent, "Step 1 of 5: Arrive");
    assert.ok(ids(doc, "day-back").disabled && !ids(doc, "day-next").disabled);
    assert.match(ids(doc, "day-counters").textContent, /Detections67Set aside0Weighed totalnot yet/);
    assert.match(ids(doc, "day-science").textContent, /calendar value, 124\.50/);
    for (let i = 1; i < DAY_STEPS.length; i += 1) {
      ids(doc, "day-next").click();
      assert.equal(widgets.day.step, i);
      assert.deepEqual(checkDocument(doc), [], `step ${i + 1}`);
    }
    assert.ok(ids(doc, "day-next").disabled);
    assert.equal(doc.querySelectorAll("#day-log li").length, 6);
    assert.equal(doc.querySelectorAll('#day-steps li[aria-current="step"]')[0].textContent, "Add up");
    assert.match(ids(doc, "day-month-text").textContent, /2\.9% of it/);
    ids(doc, "day-back").click();
    assert.equal(widgets.day.step, STEP.weigh);
    ids(doc, "day-reset").click();
    assert.equal(widgets.day.step, 0);
    assert.equal(doc.querySelectorAll("#day-log li").length, 1);
  });

  it("plays a step at a time, stops at the end, and pauses when the page loses focus or the fold closes", (t) => {
    t.mock.timers.enable({ apis: ["setTimeout"] });
    const doc = parseHtml(HTML);
    /** @type {Record<string, Function[]>} */
    const windowListeners = {};
    Object.assign(doc, { defaultView: { addEventListener: (type, fn) => (windowListeners[type] ??= []).push(fn) } });
    const { day, flare: box } = mountExplorables(/** @type {any} */ (doc), { reducedMotion: false });
    const play = ids(doc, "day-play");
    play.click();
    assert.equal(day.step, 1, "Play steps at once");
    assert.equal(play.textContent, "Pause");
    t.mock.timers.tick(STEP_DELAY.day);
    assert.equal(day.step, 2);
    t.mock.timers.tick(STEP_DELAY.day);
    t.mock.timers.tick(STEP_DELAY.day);
    assert.equal(day.step, 4);
    assert.equal(play.textContent, "Play", "stops on the last step");
    play.click();
    assert.equal(day.step, 0, "Play again starts over");
    for (const fn of windowListeners.blur ?? []) fn();
    assert.equal(play.textContent, "Play");
    t.mock.timers.tick(STEP_DELAY.day * 2);
    assert.equal(day.step, 0, "nothing moves after the page lost focus");

    ids(doc, "flare-play").click();
    assert.equal(box.day, 2);
    for (let i = 0; i < 37; i += 1) t.mock.timers.tick(STEP_DELAY.flare);
    assert.equal(box.day, 39);
    assert.match(ids(doc, "flare-live").textContent, /^Day 39, 23 September: a spot has now shown heat on 20 days\./);
    ids(doc, "flare-more").dispatchEvent({ type: "toggle" });
    assert.equal(ids(doc, "flare-play").textContent, "Play");
    t.mock.timers.tick(STEP_DELAY.flare * 3);
    assert.equal(box.day, 39, "a closed fold does not keep playing");
  });

  it("turns Play off under reduced motion while every other control still works", () => {
    const { doc, widgets } = mount({ reducedMotion: true });
    for (const id of ["day-play", "flare-play"]) assert.ok(ids(doc, id).disabled, id);
    assert.ok(!ids(doc, "day-motion-note").hidden && !ids(doc, "flare-motion-note").hidden);
    ids(doc, "day-play").click();
    assert.equal(widgets.day.step, 0);
    ids(doc, "day-next").click();
    assert.equal(widgets.day.step, 1);
    const slider = ids(doc, "flare-day");
    slider.value = "62";
    slider.dispatchEvent({ type: "input" });
    assert.equal(widgets.flare.day, 62);
    assert.match(ids(doc, "flare-counters").textContent, /Spots flagged4/);
    assert.match(slider.getAttribute("aria-valuetext"), /^Day 62 of 90 · 16 October 2026\. Day 62, 16 October: a spot has now shown heat on 20 days/);
    assert.deepEqual(checkDocument(doc), []);
  });

  it("picks a detection with the slider or the pointer", () => {
    const { doc, widgets } = mount({ reducedMotion: false });
    const pick = ids(doc, "day-pick");
    assert.equal(pick.getAttribute("max"), String(ONE_DAY.rows.length));
    assert.equal(pick.getAttribute("value"), String(defaultPick(day) + 1));
    pick.value = "1";
    pick.dispatchEvent({ type: "input" });
    assert.equal(widgets.day.pick, 0);
    assert.match(ids(doc, "day-pick-info").textContent, /^Aqua \(MODIS\)|^S-NPP \(VIIRS\)/);
    assert.match(pick.getAttribute("aria-valuetext"), /^Detection 1 of 67: /);
    const dot = ids(doc, "day-map").querySelector('[data-i="5"]');
    ids(doc, "day-map").dispatchEvent({ type: "mouseover", target: dot });
    assert.equal(widgets.day.pick, 5);
    assert.equal(ids(doc, "day-pick").getAttribute("value"), "6");
  });

  it("keeps the flare widget in a closed fold after the day, and offers no speed choice", () => {
    const { doc } = mount({ reducedMotion: false });
    const fold = ids(doc, "flare-more");
    assert.equal(ids(doc, "flare-widget").closest("details"), fold);
    assert.ok(!fold.open);
    assert.ok(HTML.indexOf('id="day-widget"') < HTML.indexOf('id="flare-more"'));
    assert.equal(doc.querySelectorAll("select").filter((el) => /speed/.test(el.getAttribute("id") ?? "")).length, 0);
  });
});
